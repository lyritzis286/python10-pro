def swap(a:int, b:int) -> tuple[int, int]:
    """Ανταλλάσσει τις τιμές των δύο ακέραιων αριθμών a και b.

    Args:
        a (int): Ο πρώτος ακέραιος αριθμός.
        b (int): Ο δεύτερος ακέραιος αριθμός.

    Returns:
        tuple[int, int]: Ένα πλειάδα που περιέχει τις ανταλλαγμένες τιμές (b, a).
    """
    return b, a

def main() -> None:
    """Κύρια συνάρτηση για την εκτέλεση του προγράμματος."""
    a = int(input("Δώσε τον πρώτο ακέραιο αριθμό (a): "))
    b = int(input("Δώσε τον δεύτερο ακέραιο αριθμό (b): "))
    a, b = swap(a, b)
    print(f"Μετά την ανταλλαγή: a = {a}, b = {b}")